const u8 *font_get_glyph(u32 cp) {
    if (cp >= 0x20 && cp <= 0x7F) {
        return font_ascii[cp - 0x20];
    }
    if (cp >= 0x410 && cp <= 0x42F) {  /* А..Я */
        return font_cyr_upper[cp - 0x410];
    }
    if (cp >= 0x430 && cp <= 0x44F) {  /* а..я */
        return font_cyr_lower[cp - 0x430];
    }
    if (cp == 0x0401) return font_cyr_upper[5];   /* Ё → Е (упрощение) */
    if (cp == 0x0451) return font_cyr_lower[5];   /* ё → е */
    if (cp == '\r' || cp == '\n' || cp == '\t') {
        /* управляющие — рисуем пусто */
        return font_ascii[0];
    }
    return glyph_unknown;
}
